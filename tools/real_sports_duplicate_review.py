def render_generate_markdown(document: Mapping[str, Any]) -> str:
    counts = document["counts"]
    lines = [
        "# Duplicate review candidates (read-only)",
        "",
        f"- dataset fingerprint: `{document['dataset_fingerprint']}`",
        f"- candidates: **{counts['total']}** ({counts['pairs']} pairs, {counts['single_records']} single records)",
        f"- by class: {counts['by_class']}",
        f"- control shapes: {counts['control_shapes']}",
        "",
        "> Classes are diagnostics, not verdicts. Human decisions are still required.",
        "",
        "| candidate | class | ids | sport | date | kickoff | teams |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for candidate in document["candidates"][:40]:
        teams = " vs ".join(
            f"{value['home']}/{value['away']}" for value in candidate["team_names"].values()
        )
        kickoff = "/".join(str(value or "-") for value in candidate["kickoff_times"].values())
        lines.append(
            "| `{cid}` | {cls} | {ids} | {sport} | {date} | {kickoff} | {teams} |".format(
                cid=candidate["candidate_id"],
                cls=candidate["candidate_class"].split("_")[0],
                ids=", ".join(candidate["canonical_ids"]),
                sport=candidate["sport"],
                date=candidate["event_date"],
                kickoff=kickoff,
                teams=teams,
            )
        )
    if len(document["candidates"]) > 40:
        lines.append(f"| … | | | | | | {len(document['candidates']) - 40} more |")
    lines.append("")
    lines.append("## Limitations")
    for item in document["limitations"]:
        lines.append(f"- {item}")
    return "\n".join(lines)


