def _ownership_index(dataset: Dataset) -> dict[str, tuple[str, ...]]:
    ownership = analyze_canonical_ownership(dataset.matches)
    index: dict[str, tuple[str, ...]] = {}
    for cluster in ownership["duplicate_clusters"]:
        group = tuple(sorted(cluster["canonical_ids"]))
        for match_id in group:
            index[match_id] = group
    return index


def preview_reconciliation(dataset: Dataset, queue: Mapping[str, Any], validation: Mapping[str, Any]) -> dict:
    """
    Compute the impact a *future* reconciliation of reviewed candidates would have.

    Nothing is chosen, nothing is deleted and nothing is executable: the output is an
    impact statement with explicit blocking reasons.
    """
    matches = {str(match["id"]): match for match in dataset.matches}
    observed = {str(match["id"]): observation for match, observation, _a, _k in observe_canonical(dataset.matches)}
    references = _reference_index(dataset)
    ownership_index = _ownership_index(dataset)
    accepted = validation.get("accepted", {})

    entries: list[dict] = []
    affected_ids: set[str] = set()
    downstream_totals = Counter()

    for candidate in sorted(queue.get("candidates", []), key=lambda item: item["candidate_id"]):
        candidate_id = candidate["candidate_id"]
        ids = list(candidate["canonical_ids"])
        decision = accepted.get(candidate_id, {}).get("decision")

        if decision == DECISION_SAME_EVENT:
            relationship = "PROPOSED_SAME_EVENT"
        elif decision == DECISION_DIFFERENT_EVENT:
            relationship = "CONFIRMED_DISTINCT"
        elif decision == DECISION_INSUFFICIENT:
            relationship = "REVIEWED_INSUFFICIENT_EVIDENCE"
        elif decision == DECISION_FURTHER_REVIEW:
            relationship = "REVIEWED_REQUIRES_FURTHER_REVIEW"
        else:
            relationship = "UNREVIEWED"

        identity_keys = {mid: _identity_view(observed[mid]) for mid in ids if mid in observed}
        shared_scope = len({
            tuple(sorted(observed[mid].stability_scope.as_dict().items()))
            for mid in ids if mid in observed
        }) == 1
        duplicate_identity_key = len({
            (view["identity_kind"], view["identity_value"]) for view in identity_keys.values()
        }) < len(identity_keys)
        compatible = all(view["is_sufficient"] for view in identity_keys.values())

        cluster_ids: list[str] = []
        for mid in ids:
            group = ownership_index.get(mid)
            if group:
                cluster_ids = sorted(set(cluster_ids) | set(group))

        downstream = {}
        for mid in ids:
            stage_counts = {stage: len(references.get(mid, {}).get(stage, []))
                            for stage in ("prediction", "odds", "settlement", "evaluation")}
            if decision is not None:
                for stage, count in stage_counts.items():
                    downstream_totals[stage] += count
            downstream[mid] = {
                "prediction": _bounded(references.get(mid, {}).get("prediction", [])),
                "odds": _bounded(references.get(mid, {}).get("odds", [])),
                "settlement": _bounded(references.get(mid, {}).get("settlement", [])),
                "evaluation": _bounded(references.get(mid, {}).get("evaluation", [])),
                "event_metadata": {
                    "sport": matches[mid].get("sport") if mid in matches else None,
                    "event_date": matches[mid].get("date") if mid in matches else None,
                    "lifecycle_status": matches[mid].get("status") if mid in matches else None,
                    "final_score": _final_score(matches[mid]) if mid in matches else None,
                },
            }

        historical_retention = {
            "required": relationship == "PROPOSED_SAME_EVENT",
            "canonical_ids": ids,
            "reason": (
                "prediction and odds snapshot IDs are derived from match_id and settlement / "
                "evaluation IDs derive from those snapshots; historical identifiers must be "
                "retained verbatim so earlier predictions keep referring to what they were built for"
            ),
        }

        if relationship == "PROPOSED_SAME_EVENT":
            required = list(GOVERNANCE_EVIDENCE_REQUIRED)
            blocked = list(GOVERNANCE_EVIDENCE_REQUIRED) + ["PRODUCTION_WRITE_NOT_AUTHORIZED"]
            affected_ids.update(ids)
        elif relationship == "CONFIRMED_DISTINCT":
            required = ["NONE_RECONCILIATION_NOT_PROPOSED"]
            blocked = ["NO_RECONCILIATION_REQUIRED"]
        else:
            required = ["HUMAN_DECISION_REQUIRED"]
            blocked = ["HUMAN_REVIEW_PENDING" if relationship == "UNREVIEWED" else "EVIDENCE_INSUFFICIENT"]

        entries.append({
            "candidate_id": candidate_id,
            "candidate_class": candidate["candidate_class"],
            "canonical_ids": ids,
            "reviewer_decision": decision,
            "identity_relationship": relationship,
            "existing_ownership_conflict": bool(cluster_ids),
            "ownership_cluster": cluster_ids,
            "source_key_compatibility": {
                "all_sufficient": compatible,
                "shared_stability_scope": shared_scope,
                "duplicate_identity_key": duplicate_identity_key,
                "identity_keys": identity_keys,
            },
            "downstream_references": downstream,
            "historical_id_retention": historical_retention,
            "governance_evidence_required": required,
            "safe_decision_possible": False,
            "blocked_reasons": blocked,
            "surviving_canonical_id": None,
            "survivor_selection_reason": (
                "preview never selects a survivor: lexical order, namespace tier and "
                "'lacks a competition number' are explicitly rejected as selection criteria"
            ),
            "proposed_operations": [],
        })

    return {
        "kind": PREVIEW_KIND,
        "schema_version": REVIEW_SCHEMA_VERSION,
        "dataset_fingerprint": queue.get("dataset_fingerprint"),
        "candidate_count": len(entries),
        "reviewed_count": len(accepted),
        "pending_count": int(validation.get("pending_count", 0)),
        "summary": {
            "proposed_same_event": sum(1 for e in entries if e["identity_relationship"] == "PROPOSED_SAME_EVENT"),
            "confirmed_distinct": sum(1 for e in entries if e["identity_relationship"] == "CONFIRMED_DISTINCT"),
            "unreviewed": sum(1 for e in entries if e["identity_relationship"] == "UNREVIEWED"),
            "canonical_records_in_proposed_merges": len(affected_ids),
            "downstream_references_touched": dict(sorted(downstream_totals.items())),
        },
        "entries": entries,
        "executable": False,
        "apply_available": False,
        "production_write_authorization": False,
        "no_mutation_performed": True,
        "decision": "NO-GO",
        "note": (
            "Impact analysis only. No Canonical record was modified, merged or deleted; "
            "no repair manifest was produced."
        ),
    }


