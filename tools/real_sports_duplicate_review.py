def _reference_index(dataset: Dataset) -> dict[str, dict[str, list[str]]]:
    """``match_id -> {store: [record ids]}`` for the four downstream stores."""
    index: dict[str, dict[str, list[str]]] = defaultdict(
        lambda: {"prediction": [], "odds": [], "settlement": [], "evaluation": []}
    )
    for stage, collection in (
        ("prediction", dataset.prediction_snapshots),
        ("odds", dataset.odds_snapshots),
        ("settlement", dataset.settlements),
        ("evaluation", dataset.evaluation_rows),
    ):
        for record_id in sorted(collection):
            match_id = str(collection[record_id].get("match_id") or "")
            if match_id:
                index[match_id][stage].append(record_id)
    return index


def _bounded(ids: Sequence[str], limit: int = 5) -> dict[str, Any]:
    ordered = sorted(ids)
    return {
        "count": len(ordered),
        "ids": ordered[:limit],
        "truncated": max(0, len(ordered) - limit),
    }


def _identity_view(observation: Any) -> dict[str, Any]:
    key = ScopedSourceIdentityKey.for_observation(observation)
    return {
        "identity_kind": key.identity_kind,
        "identity_value": key.identity_value,
        "is_sufficient": key.is_sufficient,
        "identity_key_fingerprint": key.fingerprint(),
        "provider_id_uniqueness_scope": key.provider_id_uniqueness_scope,
    }


def _source_view(observation: Any, match: Mapping[str, Any]) -> dict[str, Any]:
    adapter, known = adapter_for_match_id(match.get("id"))
    return {
        "canonical_id": str(match.get("id")),
        "derived_source_id": observation.derived_source_id,
        "source_namespace": observation.source_namespace,
        "adapter": adapter,
        "adapter_inferred": not known,
        "raw_provider_id": observation.raw_provider_id,
        "raw_identifier_type": observation.raw_provider_id_type,
        "identifier_stability": observation.identifier_stability,
        "competition_number_raw": observation.competition_number_raw,
        "competition_number_normalized": observation.competition_number_normalized,
        "kickoff_time": _kickoff_time(match),
        "kickoff_time_known": observation.kickoff_time_known,
        "lifecycle_status": match.get("status"),
        "final_score": _final_score(match),
    }


def _agreement(left: Mapping[str, Any], right: Mapping[str, Any]) -> dict[str, bool]:
    return {
        "sport": bool(left.get("sport")) and left.get("sport") == right.get("sport"),
        "event_date": bool(left.get("date")) and left.get("date") == right.get("date"),
        "competition": bool(left.get("league"))
        and _norm_team(left.get("league")) == _norm_team(right.get("league")),
        "kickoff_time": _kickoff_time(left) is not None
        and _kickoff_time(left) == _kickoff_time(right),
        "final_score": _final_score(left) is not None
        and _final_score(left) == _final_score(right),
    }


