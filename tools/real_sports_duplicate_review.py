def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Offline duplicate-event review and read-only Canonical reconciliation preview. "
            "Never writes protected stores and never authorises a merge."
        )
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--data-dir", default=None, help="directory holding the seven protected stores")
    common.add_argument("--output", default=None, help="write the JSON document to this local path")
    common.add_argument("--markdown", default=None, help="write the human-readable summary to this path")
    common.add_argument("--quiet", action="store_true", help="do not print the Markdown summary")
    common.add_argument("--json", action="store_true", help="print the JSON document to stdout")

    generate = subparsers.add_parser("generate", parents=[common], help="generate review candidates")
    generate.add_argument("--max-controls", type=int, default=DEFAULT_MAX_CONTROLS,
                          help="maximum negative controls per shape")

    validate = subparsers.add_parser("validate", parents=[common], help="validate human review decisions")
    validate.add_argument("--reviews", required=True, help="review decision file to validate")

    preview = subparsers.add_parser("preview", parents=[common], help="preview reconciliation impact")
    preview.add_argument("--reviews", required=True, help="review decision file to validate and preview")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_arg_parser().parse_args(list(argv) if argv is not None else None)
    try:
        dataset = load_dataset(args.data_dir)
    except AuditInputError as exc:
        print(f"REVIEW INPUT ERROR: {exc}", file=sys.stderr)
        return EXIT_INPUT_ERROR

    try:
        if args.command == "generate":
            document = command_generate(dataset, max_controls=max(1, args.max_controls))
            markdown = render_generate_markdown(document)
            rejected = 0
        elif args.command == "validate":
            document = command_validate(dataset, args.reviews)
            markdown = render_validation_markdown(document)
            rejected = document["rejected_count"]
        else:
            document = command_preview(dataset, args.reviews)
            markdown = render_preview_markdown(document)
            rejected = document["validation"]["rejected_count"]
    except ReviewInputError as exc:
        print(f"REVIEW INPUT ERROR: {exc}", file=sys.stderr)
        return EXIT_INPUT_ERROR

    if not document.get("stores_unchanged", True):
        print("REVIEW ABORTED: protected store changed during the read-only run", file=sys.stderr)
        return EXIT_PROTECTED_PATH

    try:
        if args.output:
            write_json(args.output, document)
        if args.markdown:
            write_text(args.markdown, markdown)
    except ProtectedOutputError as exc:
        print(f"REVIEW ABORTED: {exc}", file=sys.stderr)
        return EXIT_PROTECTED_PATH

    if args.json:
        print(json.dumps(document, ensure_ascii=False, sort_keys=True, indent=2))
    elif not args.quiet:
        print(markdown)

    if rejected:
        print(f"REVIEW REJECTED: {rejected} record(s) failed validation", file=sys.stderr)
        return EXIT_REVIEW_REJECTED
    return EXIT_OK


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())