def command_validate(dataset: Dataset, reviews_path: str) -> dict:
    queue = generate_candidates(dataset)
    document = validate_reviews(queue, load_reviews(reviews_path))
    document["stores_unchanged"] = verify_protected_stores(dataset) == dataset.hashes()
    return document


def command_preview(dataset: Dataset, reviews_path: str) -> dict:
    queue = generate_candidates(dataset)
    validation = validate_reviews(queue, load_reviews(reviews_path))
    preview = preview_reconciliation(dataset, queue, validation)
    preview["validation"] = {
        "reviewed_count": validation["reviewed_count"],
        "pending_count": validation["pending_count"],
        "rejected_count": validation["rejected_count"],
        "label_status": validation["label_status"],
    }
    preview["stores_unchanged"] = verify_protected_stores(dataset) == dataset.hashes()
    return preview


