def _pair_key(ids: Sequence[str]) -> tuple[str, ...]:
    return tuple(sorted(str(item) for item in ids))


def _evidence_quality(label: str, relations: Sequence[str]) -> str:
    if label == "SAME_EVENT":
        return "HIGH_FIELD_EVIDENCE"
    if label == "AMBIGUOUS":
        return "AMBIGUOUS_FIELD_EVIDENCE"
    if label == "DIFFERENT_EVENT":
        return "CONTRADICTORY_FIELD_EVIDENCE"
    return "INSUFFICIENT_FIELD_EVIDENCE"


def _supporting_evidence(
    left: Mapping[str, Any], right: Mapping[str, Any], label: str, evidence: Mapping[str, Any]
) -> list[str]:
    supporting: list[str] = []
    agreement = _agreement(left, right)
    for field, agreed in sorted(agreement.items()):
        if agreed:
            supporting.append(f"{field} agrees: {left.get(field) or left.get('date') or ''}".rstrip())
    if evidence.get("left_number") is not None and evidence.get("left_number") == evidence.get("right_number"):
        supporting.append(f"competition number agrees: {evidence['left_number']}")
    if label == "SAME_EVENT":
        supporting.append(f"field-evidence label: {evidence.get('reason')}")
    return supporting


def _contradictory_evidence(evidence: Mapping[str, Any]) -> list[str]:
    reason = evidence.get("reason")
    items: list[str] = []
    if reason:
        items.append(f"field-evidence reason: {reason}")
    for field in ("home_relation", "away_relation"):
        relation = evidence.get(field)
        if relation and relation != "EXACT":
            items.append(f"{field}: {relation}")
    for field in ("left_kickoff", "right_kickoff", "left_number", "right_number"):
        if evidence.get(field) is not None:
            items.append(f"{field}: {evidence[field]}")
    return items


def _build_candidate_payload(
    *,
    dataset_fp: str,
    canonical_sha: str,
    candidate_class: str,
    secondary: Sequence[str],
    canonical_ids: Sequence[str],
    matches: Mapping[str, Mapping[str, Any]],
    observations: Mapping[str, Any],
    references: Mapping[str, Mapping[str, Sequence[str]]],
    label: str,
    evidence: Mapping[str, Any],
    basis: Mapping[str, Any],
    control_shape: str | None = None,
) -> dict:
    ids = sorted(str(item) for item in canonical_ids)
    sources = {mid: _source_view(observations[mid], matches[mid]) for mid in ids}
    relations = [
        evidence.get("home_relation"),
        evidence.get("away_relation"),
    ]
    payload: dict[str, Any] = {
        "candidate_schema_version": CANDIDATE_SCHEMA_VERSION,
        "canonical_ids": ids,
        "candidate_class": candidate_class,
        "secondary_classes": sorted(set(secondary) - {candidate_class}, key=lambda c: CLASS_ORDER.get(c, 99)),
        "pair_shape": "PAIR" if len(ids) > 1 else "SINGLE_RECORD",
        "source_data_sha256": canonical_sha,
        "dataset_fingerprint": dataset_fp,
        "sport": matches[ids[0]].get("sport"),
        "event_date": matches[ids[0]].get("date"),
        "competition": {mid: matches[mid].get("league") for mid in ids},
        "kickoff_times": {mid: _kickoff_time(matches[mid]) for mid in ids},
        "team_names": {
            mid: {"home": matches[mid].get("home"), "away": matches[mid].get("away")}
            for mid in ids
        },
        "source_identifiers": sources,
        "normalized_competition_numbers": {
            mid: sources[mid]["competition_number_normalized"] for mid in ids
        },
        "lifecycle_status": {mid: matches[mid].get("status") for mid in ids},
        "final_scores": {mid: _final_score(matches[mid]) for mid in ids},
        "prediction_references": {mid: _bounded(references.get(mid, {}).get("prediction", [])) for mid in ids},
        "odds_references": {mid: _bounded(references.get(mid, {}).get("odds", [])) for mid in ids},
        "settlement_references": {mid: _bounded(references.get(mid, {}).get("settlement", [])) for mid in ids},
        "evaluation_references": {mid: _bounded(references.get(mid, {}).get("evaluation", [])) for mid in ids},
        "classification_basis": dict(basis),
        "field_evidence_label": label,
        "field_evidence_reason": evidence.get("reason"),
        "supporting_evidence": _supporting_evidence(matches[ids[0]], matches[ids[-1]], label, evidence)
        if len(ids) > 1
        else [f"identity key insufficient: {basis.get('identity_kind', UNREVIEWED)}"],
        "contradictory_evidence": _contradictory_evidence(evidence) if len(ids) > 1 else [],
        "evidence_quality": _evidence_quality(label, relations),
        "reviewer_status": UNREVIEWED,
        "review_provenance": "NONE",
        "requires_human_review": True,
    }
    if control_shape:
        payload["control_shape"] = control_shape
    payload["candidate_id"] = candidate_id_for(dataset_fp, candidate_class, ids)
    payload["candidate_fingerprint"] = candidate_fingerprint(payload)
    return payload


def candidate_id_for(dataset_fp: str, candidate_class: str, ids: Sequence[str]) -> str:
    """Reproducible candidate identity bound to the dataset and the involved records."""
    return "CAND-" + fingerprint(
        {
            "dataset_fingerprint": dataset_fp,
            "candidate_class": candidate_class,
            "canonical_ids": sorted(ids),
        }
    )[:24]


def candidate_fingerprint(payload: Mapping[str, Any]) -> str:
    """Fingerprint of the evidence payload (review fields and IDs excluded)."""
    evidence = {
        key: value
        for key, value in payload.items()
        if key not in {"candidate_id", "candidate_fingerprint", "reviewer_status", "review_provenance"}
    }
    return fingerprint(evidence)


def generate_candidates(dataset: Dataset, *, max_controls: int = DEFAULT_MAX_CONTROLS) -> dict:
    """
    Build the deterministic review queue for the supplied dataset (read-only).

    No label is produced here: every candidate starts ``UNREVIEWED`` and carries the
    evidence a human needs to decide.
    """
    matches = {str(match["id"]): match for match in dataset.matches}
    observed = {str(match["id"]): observation for match, observation, _a, _k in observe_canonical(dataset.matches)}
    references = _reference_index(dataset)
    dataset_fp = dataset_fingerprint(dataset)
    canonical_sha = dataset.hashes().get(CANONICAL_STORE, "")

    candidates: dict[tuple[str, ...], dict[str, Any]] = {}
    classes: dict[str, set[str]] = defaultdict(set)

    def add(candidate: dict[str, Any]) -> None:
        key = _pair_key(candidate["canonical_ids"])
        existing = candidates.get(key)
        classes[key].add(candidate["candidate_class"])
        if existing is None:
            candidates[key] = candidate
            return
        winner, loser = (
            (candidate, existing)
            if CLASS_ORDER[candidate["candidate_class"]] < CLASS_ORDER[existing["candidate_class"]]
            else (existing, candidate)
        )
        # The weaker classification is preserved as a secondary label either way, so
        # an insufficient-identity record inside an ambiguous pair is never lost.
        winner["secondary_classes"] = sorted(
            set(winner.get("secondary_classes", []))
            | set(loser.get("secondary_classes", []))
            | {loser["candidate_class"]},
            key=lambda name: CLASS_ORDER.get(name, 99),
        )
        candidates[key] = winner

    # 1) Pairwise scan of every (sport, date) bucket.
    buckets: dict[tuple[Any, Any], list[str]] = defaultdict(list)
    for match_id, match in matches.items():
        buckets[(match.get("sport"), match.get("date"))].append(match_id)

    control_pool: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for bucket_key in sorted(buckets, key=lambda item: (str(item[0]), str(item[1]))):
        ids = sorted(buckets[bucket_key])
        for left_index in range(len(ids)):
            for right_index in range(left_index + 1, len(ids)):
                left_id, right_id = ids[left_index], ids[right_index]
                left, right = matches[left_id], matches[right_id]
                label, evidence = classify_pair_evidence(left, right)
                relations = [evidence.get("home_relation"), evidence.get("away_relation")]
                if label == "SAME_EVENT":
                    add(_build_candidate_payload(
                        dataset_fp=dataset_fp, canonical_sha=canonical_sha,
                        candidate_class=CLASS_HIGH, secondary=[],
                        canonical_ids=[left_id, right_id],
                        matches=matches, observations=observed, references=references,
                        label=label, evidence=evidence,
                        basis={"classification_rule": "unanimous_field_evidence"},
                    ))
                elif label == "AMBIGUOUS" and "ABBREVIATION" in relations:
                    add(_build_candidate_payload(
                        dataset_fp=dataset_fp, canonical_sha=canonical_sha,
                        candidate_class=CLASS_AMBIGUOUS, secondary=[],
                        canonical_ids=[left_id, right_id],
                        matches=matches, observations=observed, references=references,
                        label=label, evidence=evidence,
                        basis={"classification_rule": "truncated_team_name"},
                    ))
                elif label == "AMBIGUOUS":
                    control_pool[_control_shape(evidence, left, right)].append((left_id, right_id))
                else:
                    control_pool[_control_shape(evidence, left, right)].append((left_id, right_id))

    # 1b) Controls that cannot appear inside one (sport, date) bucket.
    by_team_pair: dict[tuple[str, str, str], list[str]] = defaultdict(list)
    by_team_names: dict[tuple[str, str], list[str]] = defaultdict(list)
    for match_id in sorted(matches):
        match = matches[match_id]
        home, away = _norm_team(match.get("home")), _norm_team(match.get("away"))
        if not home or not away:
            continue
        by_team_pair[(str(match.get("sport")), home, away)].append(match_id)
        by_team_names[(home, away)].append(match_id)

    for key in sorted(by_team_pair):
        ids = by_team_pair[key]
        for left_index in range(len(ids)):
            for right_index in range(left_index + 1, len(ids)):
                left_id, right_id = ids[left_index], ids[right_index]
                if matches[left_id].get("date") != matches[right_id].get("date"):
                    control_pool["SAME_TEAMS_DIFFERENT_DATE"].append((left_id, right_id))

    for key in sorted(by_team_names):
        ids = by_team_names[key]
        for left_index in range(len(ids)):
            for right_index in range(left_index + 1, len(ids)):
                left_id, right_id = ids[left_index], ids[right_index]
                if matches[left_id].get("sport") != matches[right_id].get("sport"):
                    control_pool["DIFFERENT_SPORT_SAME_TEAMS"].append((left_id, right_id))

    # 2) Insufficient source identity: strongest association, else a single record.
    by_id_keys = {mid: ScopedSourceIdentityKey.for_observation(obs) for mid, obs in observed.items()}
    for match_id in sorted(matches):
        key = by_id_keys[match_id]
        if key.is_sufficient:
            continue
        match = matches[match_id]
        best: tuple[int, str] | None = None
        for other_id in sorted(buckets[(match.get("sport"), match.get("date"))]):
            if other_id == match_id or not by_id_keys[other_id].is_sufficient:
                continue
            relation_rank = _relation_rank(match, matches[other_id])
            if relation_rank is None:
                continue
            if best is None or relation_rank < best[0]:
                best = (relation_rank, other_id)
        observation = observed[match_id]
        if best is None:
            add(_build_candidate_payload(
                dataset_fp=dataset_fp, canonical_sha=canonical_sha,
                candidate_class=CLASS_INSUFFICIENT,
                secondary=[CLASS_INSUFFICIENT],
                canonical_ids=[match_id],
                matches=matches, observations=observed, references=references,
                label="INSUFFICIENT_EVIDENCE",
                evidence={"reason": "no sufficient-identity association in the same slot"},
                basis={
                    "classification_rule": "insufficient_identity_key",
                    "identity_kind": key.identity_kind,
                    "association_found": False,
                },
            ))
            continue
        other_id = best[1]
        label, evidence = classify_pair_evidence(match, matches[other_id])
        add(_build_candidate_payload(
            dataset_fp=dataset_fp, canonical_sha=canonical_sha,
            candidate_class=CLASS_INSUFFICIENT,
            secondary=[CLASS_AMBIGUOUS] if label == "AMBIGUOUS" else [],
            canonical_ids=[match_id, other_id],
            matches=matches, observations=observed, references=references,
            label=label, evidence=evidence,
            basis={
                "classification_rule": "insufficient_identity_association",
                "identity_kind": key.identity_kind,
                "association_found": True,
                "association_evidence_label": label,
                "checkout_time": observation.kickoff_time,
            },
        ))

    # 3) Negative controls, bounded per shape, excluding pairs already queued.
    for shape in sorted(control_pool):
        for left_id, right_id in sorted(control_pool[shape])[:max_controls]:
            if _pair_key([left_id, right_id]) in candidates:
                continue
            label, evidence = classify_pair_evidence(matches[left_id], matches[right_id])
            add(_build_candidate_payload(
                dataset_fp=dataset_fp, canonical_sha=canonical_sha,
                candidate_class=CLASS_CONTROL, secondary=[],
                canonical_ids=[left_id, right_id],
                matches=matches, observations=observed, references=references,
                label=label, evidence=evidence,
                basis={"classification_rule": "negative_control", "control_shape": shape},
                control_shape=shape,
            ))

    # Fingerprints are computed last: merging can add secondary classes, and the
    # fingerprint must describe the final diagnostic identity, not an intermediate one.
    for candidate in candidates.values():
        candidate["candidate_fingerprint"] = candidate_fingerprint(candidate)

    ordered = sorted(
        candidates.values(),
        key=lambda item: (CLASS_ORDER[item["candidate_class"]], item["candidate_id"]),
    )
    by_class = Counter(item["candidate_class"] for item in ordered)
    return {
        "kind": GENERATE_KIND,
        "candidate_schema_version": CANDIDATE_SCHEMA_VERSION,
        "review_schema_version": REVIEW_SCHEMA_VERSION,
        "dataset_fingerprint": dataset_fp,
        "dataset_sha256": dataset.hashes(),
        "counts": {
            "total": len(ordered),
            "pairs": sum(1 for item in ordered if item["pair_shape"] == "PAIR"),
            "single_records": sum(1 for item in ordered if item["pair_shape"] == "SINGLE_RECORD"),
            "by_class": {name: by_class.get(name, 0) for name in sorted(by_class, key=lambda c: CLASS_ORDER[c])},
            "control_shapes": dict(sorted(Counter(
                item["control_shape"] for item in ordered if item.get("control_shape")
            ).items())),
        },
        "candidates": ordered,
        "review_template": {
            "kind": "READ_ONLY_DUPLICATE_REVIEW_DECISIONS",
            "schema_version": REVIEW_SCHEMA_VERSION,
            "dataset_fingerprint": dataset_fp,
            "reviews": [],
        },
        "label_provenance": "CANDIDATE_DIAGNOSTICS_ONLY",
        "human_labels_present": False,
        "production_write_authorization": False,
        "limitations": [
            "Candidate classes are diagnostics produced from field evidence; they are not verdicts.",
            "No precision or recall is computable without independent reviewed decisions.",
            "However many records are listed, the queue is generated, not human-reviewed.",
        ],
    }


def _control_shape(
    evidence: Mapping[str, Any],
    left: Mapping[str, Any] | None = None,
    right: Mapping[str, Any] | None = None,
) -> str:
    reason = str(evidence.get("reason") or "")
    mapping = {
        "event date mismatch": "SAME_TEAMS_DIFFERENT_DATE",
        "kickoff time disagreement": "SAME_TEAMS_DIFFERENT_KICKOFF",
        "league disagreement": "DIFFERENT_COMPETITION",
        "competition number disagreement": "CONFLICTING_COMPETITION_NUMBER",
        "final score disagreement": "CONFLICTING_FINAL_SCORE",
        "sport mismatch": "DIFFERENT_SPORT",
    }
    if reason in mapping:
        return mapping[reason]
    if left is not None and right is not None and _name_similarity_bait(left, right):
        return "SIMILAR_TEAM_NAMES"
    return "DIFFERENT_TEAMS"


def _shares_prefix(left: Any, right: Any, minimum: int = 2) -> bool:
    norm_left, norm_right = _norm_team(left), _norm_team(right)
    if len(norm_left) < minimum or len(norm_right) < minimum:
        return False
    return norm_left[:minimum] == norm_right[:minimum] and norm_left != norm_right


def _name_similarity_bait(left: Mapping[str, Any], right: Mapping[str, Any]) -> bool:
    """True when the pair looks mergeable by name but the evidence contradicts it."""
    return _shares_prefix(left.get("home"), right.get("home")) or _shares_prefix(
        left.get("away"), right.get("away")
    )


def _relation_rank(match: Mapping[str, Any], other: Mapping[str, Any]) -> int | None:
    ranks = {"EXACT": 0, "NORMALIZED_EQUAL": 1, "ABBREVIATION": 2}
    home = team_relation(match.get("home"), other.get("home"))
    away = team_relation(match.get("away"), other.get("away"))
    if home not in ranks or away not in ranks:
        return None
    return max(ranks[home], ranks[away])


