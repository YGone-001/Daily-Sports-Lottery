def dataset_fingerprint(dataset: Dataset) -> str:
    """Stable fingerprint over the exact bytes of the seven protected stores."""
    return fingerprint(
        {
            "kind": "DUPLICATE_REVIEW_DATASET_IDENTITY",
            "schema_version": REVIEW_SCHEMA_VERSION,
            "stores": dataset.hashes(),
        }
    )


def validate_output_path(path: str) -> str:
    """
    Refuse output inside ``data/``, inside any protected production root, or anywhere
    inside the checkout that is not the Git-ignored ``reports/`` directory.
    """
    if not path:
        raise ProtectedOutputError("an explicit output path is required")
    resolved = canonicalize_path(path)
    reports_dir = canonicalize_path(os.path.join(SOURCE_REPO_ROOT, "reports"))
    if is_subpath_or_equal(resolved, reports_dir):
        return path
    data_dir = canonicalize_path(os.path.join(SOURCE_REPO_ROOT, "data"))
    if is_subpath_or_equal(resolved, data_dir):
        raise ProtectedOutputError(f"refusing to write inside the Canonical data directory: {path}")
    for protected in (PROD_REPO_ROOT, SOURCE_REPO_ROOT):
        if protected and is_subpath_or_equal(resolved, protected):
            raise ProtectedOutputError(
                f"refusing to write inside a protected checkout: {path}"
            )
    return path


def write_json(path: str, payload: Mapping[str, Any]) -> None:
    """Write deterministic JSON to a validated local path."""
    validate_output_path(path)
    directory = os.path.dirname(os.path.abspath(path))
    if directory and not os.path.isdir(directory):
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, ensure_ascii=False, sort_keys=True, indent=2)
        handle.write("\n")


def write_text(path: str, text: str) -> None:
    validate_output_path(path)
    directory = os.path.dirname(os.path.abspath(path))
    if directory and not os.path.isdir(directory):
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
        if not text.endswith("\n"):
            handle.write("\n")


