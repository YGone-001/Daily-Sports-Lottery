def _collect_keys(payload: Any, prefix: str = "") -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    if isinstance(payload, Mapping):
        for key, value in payload.items():
            name = str(key)
            found.append((name, f"{prefix}{name}"))
            found.extend(_collect_keys(value, f"{prefix}{name}."))
    elif isinstance(payload, list):
        for index, value in enumerate(payload):
            found.extend(_collect_keys(value, f"{prefix}{index}."))
    return found


def load_reviews(path: str) -> dict:
    """Strict reader for a local review-decision file (no side effects)."""
    if not os.path.isfile(path):
        raise ReviewInputError(f"review file not found: {path}")
    try:
        with open(path, "r", encoding="utf-8") as handle:
            payload = json.load(handle)
    except json.JSONDecodeError as exc:
        raise ReviewInputError(f"malformed review JSON ({exc})") from exc
    except OSError as exc:
        raise ReviewInputError(f"unreadable review file ({exc})") from exc
    if not isinstance(payload, Mapping):
        raise ReviewInputError("review file must contain a JSON object")
    return dict(payload)


def _reject(candidate_id: str | None, code: str, detail: str, index: int | None = None) -> dict:
    return {
        "candidate_id": candidate_id,
        "reason_code": code,
        "detail": detail,
        "record_index": index,
    }


def _parse_timestamp(value: Any) -> bool:
    from datetime import datetime

    if not isinstance(value, str) or not value.strip():
        return False
    try:
        datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return False
    return True


def validate_reviews(queue: Mapping[str, Any], reviews_document: Mapping[str, Any]) -> dict:
    """
    Validate independent review decisions against a generated queue.

    Every record is checked against the exact candidate identity and dataset; a record
    that cannot be bound is rejected rather than reinterpreted.
    """
    rejected: list[dict] = []
    accepted: dict[str, dict] = {}
    by_candidate: dict[str, list[dict]] = defaultdict(list)

    schema_version = reviews_document.get("schema_version")
    dataset_fp = queue.get("dataset_fingerprint")
    raw_reviews = reviews_document.get("reviews")

    if schema_version != REVIEW_SCHEMA_VERSION:
        rejected.append(_reject(None, "UNSUPPORTED_SCHEMA_VERSION",
                                f"expected {REVIEW_SCHEMA_VERSION!r}, got {schema_version!r}"))
    if reviews_document.get("dataset_fingerprint") != dataset_fp:
        rejected.append(_reject(None, "DATASET_FINGERPRINT_MISMATCH",
                                "review file is bound to a different dataset"))
    if not isinstance(raw_reviews, list):
        raise ReviewInputError("review file must contain a 'reviews' list")

    candidates = {item["candidate_id"]: item for item in queue.get("candidates", [])}

    for index, record in enumerate(raw_reviews):
        if not isinstance(record, Mapping):
            rejected.append(_reject(None, "MALFORMED_REVIEW_RECORD", "review record is not an object", index))
            continue
        record = dict(record)

        prohibited = [
            (name, path) for name, path in _collect_keys(record)
            if name.lower() in PROHIBITED_REVIEW_KEYS
        ]
        if prohibited:
            rejected.append(_reject(
                str(record.get("candidate_id") or "") or None,
                "PROHIBITED_REVIEW_FIELD",
                "review payload carries production-authorization or mutation semantics: "
                + ", ".join(sorted({path for _name, path in prohibited})),
                index,
            ))
            continue

        missing = sorted(REVIEW_RECORD_KEYS - set(record))
        if missing:
            rejected.append(_reject(
                str(record.get("candidate_id") or "") or None,
                "INCOMPLETE_REVIEW",
                f"missing required fields: {missing}",
                index,
            ))
            continue

        candidate_id = str(record.get("candidate_id"))
        decision = record.get("decision")
        provenance = record.get("label_provenance")

        if decision == UNREVIEWED:
            rejected.append(_reject(candidate_id, "INCOMPLETE_REVIEW",
                                    "an absent decision means UNREVIEWED; a record must decide", index))
            continue
        if decision not in DECIDED_VALUES:
            rejected.append(_reject(candidate_id, "UNSUPPORTED_DECISION",
                                    f"unsupported decision {decision!r}", index))
            continue
        if provenance != PROVENANCE_HUMAN:
            rejected.append(_reject(
                candidate_id, "AUTOMATED_LABEL_REJECTED",
                f"label_provenance must be {PROVENANCE_HUMAN!r}; automated labels cannot "
                "stand in for human review",
                index,
            ))
            continue
        reviewer = record.get("reviewer")
        if not isinstance(reviewer, str) or not reviewer.strip():
            rejected.append(_reject(candidate_id, "MISSING_REVIEWER",
                                    "reviewer identity string is required", index))
            continue
        if not _parse_timestamp(record.get("decided_at")):
            rejected.append(_reject(candidate_id, "INVALID_TIMESTAMP",
                                    "decided_at must be an ISO-8601 timestamp", index))
            continue
        reference = record.get("evidence_reference")
        if not isinstance(reference, str) or not reference.strip():
            rejected.append(_reject(candidate_id, "MISSING_EVIDENCE_REFERENCE",
                                    "evidence_reference is required", index))
            continue
        if not isinstance(record.get("notes"), str):
            rejected.append(_reject(candidate_id, "INVALID_NOTES",
                                    "notes must be a string (may be empty)", index))
            continue
        if record.get("dataset_fingerprint") != dataset_fp:
            rejected.append(_reject(candidate_id, "DATASET_FINGERPRINT_MISMATCH",
                                    "review record is bound to a different dataset", index))
            continue

        candidate = candidates.get(candidate_id)
        if candidate is None:
            rejected.append(_reject(candidate_id, "UNKNOWN_CANDIDATE",
                                    "candidate_id is not present in this queue", index))
            continue
        if record.get("candidate_fingerprint") != candidate.get("candidate_fingerprint"):
            rejected.append(_reject(candidate_id, "STALE_CANDIDATE_FINGERPRINT",
                                    "candidate evidence changed since the review was recorded", index))
            continue
        record_ids = record.get("canonical_ids")
        if not isinstance(record_ids, list) or sorted(str(i) for i in record_ids) != sorted(candidate["canonical_ids"]):
            rejected.append(_reject(candidate_id, "CANONICAL_IDS_MISMATCH",
                                    "canonical_ids do not match the candidate", index))
            continue

        by_candidate[candidate_id].append(
            {**record, "_index": index, "candidate_class": candidate["candidate_class"]}
        )

    for candidate_id in sorted(by_candidate):
        records = sorted(by_candidate[candidate_id], key=lambda item: (str(item["decided_at"]), item["_index"]))
        distinct = {item["decision"] for item in records}
        if len(distinct) > 1:
            for item in records:
                rejected.append(_reject(
                    candidate_id, "CONFLICTING_LABEL",
                    "the same candidate carries contradictory human decisions: "
                    + ", ".join(sorted(distinct)),
                    item["_index"],
                ))
            continue
        accepted[candidate_id] = records[0]
        if len(records) > 1:
            for item in records[1:]:
                rejected.append(_reject(
                    candidate_id, "DUPLICATE_DECISION",
                    "candidate was decided more than once with the same label",
                    item["_index"],
                ))

    pending = sorted(cid for cid in candidates if cid not in accepted)
    decisions_by_class: dict[str, Counter] = defaultdict(Counter)
    for candidate_id, record in accepted.items():
        decisions_by_class[record["candidate_class"]][record["decision"]] += 1

    reviewed = len(accepted)
    total = len(candidates)
    if not accepted:
        label_status = "NOT_COMPUTABLE_NO_HUMAN_DECISIONS"
    elif reviewed < total:
        label_status = "PARTIAL_SAMPLE"
    else:
        label_status = "COMPLETE_SAMPLE_SELF_DECLARED"

    return {
        "kind": VALIDATION_KIND,
        "schema_version": REVIEW_SCHEMA_VERSION,
        "dataset_fingerprint": dataset_fp,
        "candidate_count": total,
        # Carry the accepted record **verbatim** (minus the internal row index) so a
        # downstream persistence writer receives exactly what the operator wrote.
        # The durable evidence schema requires the identity fields the previous
        # trimmed projection dropped, so trimming here made every real persistence
        # attempt fail closed with `INCOMPLETE_RECORD`. `candidate_class` stays in
        # the payload as a queue-side diagnostic; consumers that write records must
        # project onto their own schema instead of mutating this one.
        "accepted": {
            cid: {key: value for key, value in accepted[cid].items() if key != "_index"}
            for cid in sorted(accepted)
        },
        "rejected": rejected,
        "rejected_count": len(rejected),
        "pending": pending,
        "pending_count": len(pending),
        "reviewed_count": reviewed,
        "coverage": round(reviewed / total, 4) if total else None,
        "label_provenance": "SELF_DECLARED_LOCAL_HUMAN_REVIEW",
        "label_status": label_status,
        "decisions_by_class": {
            name: dict(sorted(counter.items())) for name, counter in sorted(decisions_by_class.items())
        },
        "precision": None,
        "recall": None,
        "accuracy_claim": (
            "NOT_CLAIMED: self-declared local decisions are audit metadata, not "
            "authenticated organizational labels; no precision or recall is derived."
        ),
    }


