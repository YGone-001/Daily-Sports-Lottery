"""
tools/real_sports_duplicate_review.py
=====================================
Offline, read-only duplicate-event review and Canonical reconciliation **preview**.

What this tool is
-----------------
A working local workflow that lets a human look at *possible* duplicate sports events,
record an independent decision, and see the impact a future reconciliation would have —
without touching a single production record.

What this tool is not
---------------------
- It is **not** an approval system. A reviewer identity is self-declared audit metadata,
  not a signed organizational approval. ``utils/mapping_governance`` remains the only
  authority that can bind a source to a Canonical owner, and it is not used here.
- It is **not** a merge tool. ``preview`` never selects a surviving Canonical ID, never
  deletes a weaker record and never emits an executable repair plan.
- It is **not** a source-identity engine. All identity classification is delegated to the
  existing implementations (``utils/source_identity``) through
  ``tools.real_sports_identity_audit``; this module adds candidate presentation and
  human-review bookkeeping only.

Diagnostic classes (never human verdicts)
-----------------------------------------
``HIGH_EVIDENCE_DUPLICATE_CANDIDATE``
    Field evidence is unanimous (teams, date, kickoff, competition, numbers, result).
``AMBIGUOUS_NAME_CANDIDATE``
    Same slot, but at least one team name is truncated/abbreviated — equality is not
    established by field evidence.
``INSUFFICIENT_SOURCE_IDENTITY``
    A record whose scoped identity key cannot authorise an active binding; optionally
    paired with the strongest available association candidate.
``NEGATIVE_CONTROL_CANDIDATE``
    Deliberately *different* (or evidently conflicting) pairs, included so a reviewer can
    demonstrate that the queue does not only contain merge candidates.

Hard constraints
----------------
1. Read-only: protected stores are opened for reading only; their SHA-256 is captured
   before and after every command and any change aborts the run.
2. No network access, no scraping, no ``refresh()``.
3. Writes are refused inside ``data/`` or any protected production root. The only
   in-repository location that is allowed is the Git-ignored ``reports/`` directory;
   everything else must be outside the checkout.
4. Deterministic: every list is ordered by a stable key, so identical input bytes yield
   byte-identical JSON (no timestamps are generated by the tool).
5. Fail-closed: malformed stores, malformed review files, unknown candidates, stale
   fingerprints and contradictory labels are rejected with explicit reason codes.
"""
